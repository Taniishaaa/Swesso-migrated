// Regenerates supabase/seed/price_items.sql from:
//   stdPrices.source.json     the original price book (505 rows)
//   added_price_items.json    rows that the calculation functions look up but the book lacked; each carries the
//                             closest existing item's prices (`closest_to`) and is flagged is_estimated = true
// Usage:  node supabase/seed/generate-price-items.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const base = JSON.parse(fs.readFileSync(path.join(dir, "stdPrices.source.json"), "utf8"));
const added = JSON.parse(fs.readFileSync(path.join(dir, "added_price_items.json"), "utf8"));

// price-book header -> price_items column
const COLUMNS = [
  ["ABB", "abb"], ["MG", "mg"], ["GE", "ge"], ["CUTLERH", "cutlerh"], ["SEIMENS", "seimens"], ["LG", "lg"],
  ["L&T", "lt"], ["DSMITH", "dsmith"], ["NEW", "new_price"], ["M.BSHI", "mbshi"], ["Z", "z"],
]; // the "y" column is left NULL (brand Y has no prices yet)

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const num = (v) => {
  const n = Number(v);
  if (v === "" || v === null || v === undefined || !Number.isFinite(n)) return "NULL";
  return String(n);
};
const row = (r, estimated) =>
  `  (${q(r.CODE)}, ${q(String(r.ITEMS).trim())}, ${COLUMNS.map(([h]) => num(r[h])).join(", ")}, ${estimated})`;

const values = [...base.map((r) => row(r, false)), ...added.map((r) => row(r, true))];
const cols = ["code", "items", ...COLUMNS.map(([, c]) => c), "is_estimated"].join(", ");

const sql = `-- GENERATED by supabase/seed/generate-price-items.mjs - do not edit by hand.
-- ${base.length} rows from stdPrices.source.json + ${added.length} added rows (is_estimated = true,
-- priced at the closest existing item; see added_price_items.json "closest_to").
-- Safe to re-run: existing items are left untouched (ON CONFLICT DO NOTHING), so manual price edits are never overwritten.

insert into public.price_items (${cols}) values
${values.join(",\n")}
on conflict (items) do nothing;
`;
fs.writeFileSync(path.join(dir, "price_items.sql"), sql);
console.log(`wrote price_items.sql: ${base.length} + ${added.length} = ${values.length} rows`);
